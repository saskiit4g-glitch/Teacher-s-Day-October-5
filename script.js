function el(tag, cls, text) {
  var e = document.createElement(tag);
  if (cls) e.className = cls;
  if (text) e.textContent = text;
  return e;
}

function renderTeachers(id, list) {
  var box = document.getElementById(id);
  list.forEach(function (t, i) {
    var a = el("article", "t t" + (i % 2));
    a.appendChild(el("span", "s", t[0]));
    a.appendChild(el("h3", "", "أ. " + t[1]));
    a.appendChild(el("p", "", t[2]));
    box.appendChild(a);
  });
}

function renderLeads(id, list) {
  var box = document.getElementById(id);
  list.forEach(function (l) {
    var d = el("div", "l");
    d.appendChild(el("span", "", l[0]));
    d.appendChild(el("b", "", "أ. " + l[1]));
    box.appendChild(d);
  });
}

